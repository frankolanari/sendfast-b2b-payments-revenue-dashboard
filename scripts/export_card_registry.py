"""Card registry for the proxy and the front end (PLAN.md Stage 7), generated from queries/.

    uv run python scripts/export_card_registry.py          # write the generated files
    uv run python scripts/export_card_registry.py --check  # fail if a committed file is stale

One source of truth: queries/cards/*.sql (front matter) and queries/parameters.yml. The server
uses it as its allow-list (only these cards, only these parameters); the web app uses it for
types. Rule 3: never edit the output by hand; change the cards and regenerate.
"""

from __future__ import annotations

import argparse
import json
import sys

import card_content as mc

OUT = mc.ROOT / "web" / "src" / "api" / "cards.generated.ts"
SQL_OUT = mc.ROOT / "proxy" / "src" / "sql.generated.ts"  # server only: never in the browser


def render_sql() -> str:
    """The SQL inside the server bundle, so it needs no file system (Cloudflare Workers)."""
    sql = {
        p.stem: mc.parse_card(p.read_text(encoding="utf-8"), p.name).sql
        for p in sorted((mc.QUERY_DIR / "cards").glob("*.sql"))
    }
    return (
        "// GENERATED by scripts/export_card_registry.py from queries/cards/*.sql.\n"
        "// Do not edit by hand (rule 3): change those and regenerate.\n\n"
        f"export const cardSql: Record<string, string> = {json.dumps(sql, indent=2)};\n"
    )


def render() -> str:
    params = mc.load_parameters()
    cards = {}
    for path in sorted((mc.QUERY_DIR / "cards").glob("*.sql")):
        card = mc.parse_card(path.read_text(encoding="utf-8"), str(path.relative_to(mc.ROOT)))
        cards[path.stem] = {
            "name": card.name,
            "collection": card.collection,
            "display": card.display,
            "params": card.params,
            "required": card.required,
        }
    contract = {
        name: {
            "type": p["type"],
            "label": p["label"],
            **({"default": p["default"]} if p.get("default") is not None else {}),
            **({"values": p["values"]["static"]} if "static" in (p.get("values") or {}) else {}),
            **(
                {
                    "valuesCard": next(
                        s for s, c in cards.items() if c["name"] == p["values"]["card"]
                    )
                }
                if "card" in (p.get("values") or {})
                else {}
            ),
        }
        for name, p in params.items()
    }
    body = (
        "// GENERATED by scripts/export_card_registry.py from queries/cards/*.sql and\n"
        "// queries/parameters.yml. Do not edit by hand (rule 3): change those and regenerate.\n\n"
        f"export const parameterContract = {json.dumps(contract, indent=2)} as const;\n\n"
        f"export const cards = {json.dumps(cards, indent=2)} as const;\n\n"
        "export type ParamName = keyof typeof parameterContract;\n"
        "export type CardSlug = keyof typeof cards;\n"
    )
    return body


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    outputs = {OUT: render(), SQL_OUT: render_sql()}
    stale = [
        p for p, text in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != text
    ]
    for path, text in outputs.items():
        name = path.relative_to(mc.ROOT)
        if args.check:
            state = "stale: run make card-registry" if path in stale else "up to date"
            print(f"{name} is {state}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {name} ({text.count(chr(10))} lines)")
    return 1 if args.check and stale else 0


if __name__ == "__main__":
    sys.exit(main())
