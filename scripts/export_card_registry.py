"""Card registry for the proxy and the front end (PLAN.md Stage 7), generated from metabase/.

    uv run python scripts/export_card_registry.py          # write web/src/api/cards.generated.ts
    uv run python scripts/export_card_registry.py --check  # fail if the committed file is stale

One source of truth: metabase/cards/*.sql (front matter) and metabase/parameters.yml. The proxy
uses it as its allow-list (only these cards, only these parameters); the web app uses it for
types. Rule 3: never edit the output by hand; change the cards and regenerate.
"""

from __future__ import annotations

import argparse
import json
import sys

import metabase_content as mc

OUT = mc.ROOT / "web" / "src" / "api" / "cards.generated.ts"


def render() -> str:
    params = mc.load_parameters()
    cards = {}
    for path in sorted((mc.MB_DIR / "cards").glob("*.sql")):
        card = mc.parse_card(path.read_text(encoding="utf-8"), str(path.relative_to(mc.ROOT)))
        cards[path.stem] = {
            "name": card.name,
            "collection": card.collection,
            "display": card.display,
            "params": card.params,
            "required": card.required,
        }
    contract = {
        name: {
            "type": p["type"],
            "label": p["label"],
            **({"default": p["default"]} if p.get("default") is not None else {}),
            **({"values": p["values"]["static"]} if "static" in (p.get("values") or {}) else {}),
            **(
                {
                    "valuesCard": next(
                        s for s, c in cards.items() if c["name"] == p["values"]["card"]
                    )
                }
                if "card" in (p.get("values") or {})
                else {}
            ),
        }
        for name, p in params.items()
    }
    body = (
        "// GENERATED by scripts/export_card_registry.py from metabase/cards/*.sql and\n"
        "// metabase/parameters.yml. Do not edit by hand (rule 3): change those and regenerate.\n\n"
        f"export const parameterContract = {json.dumps(contract, indent=2)} as const;\n\n"
        f"export const cards = {json.dumps(cards, indent=2)} as const;\n\n"
        "export type ParamName = keyof typeof parameterContract;\n"
        "export type CardSlug = keyof typeof cards;\n"
    )
    return body


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(mc.ROOT)} is stale: run make card-registry")
            return 1
        print(f"{OUT.relative_to(mc.ROOT)} is up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(mc.ROOT)} ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
