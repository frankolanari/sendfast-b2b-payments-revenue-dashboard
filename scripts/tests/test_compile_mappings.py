"""Tests for scripts/compile_mappings.py: the real map compiles; broken maps are rejected."""

from __future__ import annotations

import copy
import re
from typing import Any

import compile_mappings as cm
import pytest
from contract_check import CONTRACT_PATH, load_yaml


@pytest.fixture(scope="module")
def contract() -> dict[str, Any]:
    return load_yaml(CONTRACT_PATH.read_text(encoding="utf-8"))


@pytest.fixture
def hubspot() -> dict[str, Any]:
    return cm.load_map(cm.MAPPINGS_DIR / "hubspot.yml")


def errors_for(m: dict[str, Any], contract: dict[str, Any]) -> str:
    return "\n".join(cm.validate_map(m, contract))


# ── The real map ─────────────────────────────────────────────────────────
def test_hubspot_map_is_valid(hubspot, contract):
    assert cm.validate_map(hubspot, contract) == []


def test_compile_is_deterministic(hubspot, contract):
    assert cm.compile_map(hubspot, contract) == cm.compile_map(copy.deepcopy(hubspot), contract)


def test_committed_models_are_up_to_date(hubspot, contract):
    assert cm.stale_files(cm.compile_map(hubspot, contract), cm.OUTPUT_DIR) == []


def test_every_output_has_do_not_edit_header(hubspot, contract):
    for name, content in cm.compile_map(hubspot, contract).items():
        assert "GENERATED by scripts/compile_mappings.py" in content.splitlines()[0], name
        assert "DO NOT EDIT" in content.splitlines()[0], name


def test_one_model_per_canonical_crm_table(hubspot, contract):
    sql_files = {n for n in cm.compile_map(hubspot, contract) if n.startswith("stg_")}
    expected = {f"{t['name']}.sql" for t in contract["tables"] if t["source"] == "crm"}
    assert sql_files == expected


def test_final_select_follows_contract_column_order(hubspot, contract):
    sql = cm.compile_map(hubspot, contract)["stg_crm__opportunities.sql"]
    final = sql.rsplit("\nselect\n", 1)[1]
    names = [
        re.split(r"\s+as\s+", line.strip().rstrip(","))[-1] for line in final.splitlines()[:-1]
    ]
    table = next(t for t in contract["tables"] if t["name"] == "stg_crm__opportunities")
    assert names == [c["name"] for c in table["columns"]]


def test_value_map_and_derived_columns_are_compiled(hubspot, contract):
    sql = cm.compile_map(hubspot, contract)["stg_crm__opportunities.sql"]
    assert "when 'closedwon' then 'won'" in sql
    assert "cast((stage in ('won', 'lost')) as boolean) as is_closed" in sql


def test_timestamps_are_converted_from_map_timezone(hubspot, contract):
    tz = hubspot["timezone"]
    sql = cm.compile_map(hubspot, contract)["stg_crm__opportunities.sql"]
    assert f"(cast(createdate as timestamp) at time zone '{tz}') as created_at" in sql
    hubspot["timezone"] = "Africa/Lagos"  # and it follows the map when the map changes
    sql = cm.compile_map(hubspot, contract)["stg_crm__opportunities.sql"]
    assert "(cast(createdate as timestamp) at time zone 'Africa/Lagos') as created_at" in sql


def test_filter_is_applied(hubspot, contract):
    sql = cm.compile_map(hubspot, contract)["stg_crm__opportunity_stage_history.sql"]
    assert "where property_name = 'dealstage'" in sql


def test_unmapped_model_covers_every_value_map(hubspot, contract):
    sql = cm.compile_map(hubspot, contract)["int_crm__unmapped_values.sql"]
    for entity, block in hubspot.items():
        if isinstance(block, dict):
            for column in block.get("values") or {}:
                assert f"'{entity}' as entity,\n    '{column}' as canonical_column" in sql


